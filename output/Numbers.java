package output;

public class Numbers{
    public static void main(String[] args){
        //You can print numbers to the console using the System.out.println() Method
        //This prints the number 5 of type int to the console
        System.out.println(5);

        //You can also perform numerical expressions on numbers in the System.out.Println() method
        //This will output 11 following the basic mathematical rules
        System.out.println(5 + 5);
        System.out.println(6 * 2); //Outputs 12
        System.out.println(9 / 3); //outputs 3
        System.out.println(17 - 12); //outputs 5

        //Also in the event of multple numerical expressions BODMAS will apply
        System.out.println(2 * 3 + 6 / 2); //This outputs 9
    }
}